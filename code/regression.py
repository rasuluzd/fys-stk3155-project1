# Metrics
# ----------------------------------------------------------------------------------------------
def mse(y, y_pred):
    """Mean squared error.

    Implements Week 35 Exercise 2 item 3 / Lecturebook Eq. (3.17). The denominator is the
    number of evaluated observations, which can differ from the number used in fitting.
    """
    y, y_pred = np.asarray(y).ravel(), np.asarray(y_pred).ravel()
    return np.mean((y - y_pred) ** 2)


def r2(y, y_pred):
    """Coefficient of determination R^2.

    Implements Week 35 Exercise 2 item 3 / Lecturebook Eq. (3.18). Its baseline is the mean
    of the evaluation targets, not the stored training mean. Negative scores are possible;
    the present formula assumes nonconstant evaluation targets (as in these experiments).
    """
    y, y_pred = np.asarray(y).ravel(), np.asarray(y_pred).ravel()
    return 1.0 - np.sum((y - y_pred) ** 2) / np.sum((y - np.mean(y)) ** 2)


