class PolynomialRegression(BaseEstimator, RegressorMixin):
    """Polynomial regression in x with OLS, Ridge or Lasso and built-in train-only scaling.

    Parameters
    ----------
    degree : int
        Polynomial degree p (the model has p slope parameters plus an unpenalised intercept).
    method : {"ols", "ridge", "lasso"}
    lam : float
        Penalty lambda in the 1/n-normalised cost (ignored for OLS).
    scale : bool
        Standardise the columns (True) or only centre them (False).
    solver : callable or None
        Optional function solver(X, y, lam) -> theta on the scaled data. Used to plug in our own
        gradient-descent Lasso; the default for Lasso is Scikit-Learn's coordinate descent.

    Because it follows the Scikit-Learn interface (fit/predict/get_params), it can be passed
    directly to cross_val_score, and the scaling is then refitted inside every training fold.

    The mathematical steps are the course's polynomial feature construction, training-only
    scaling, and regression fit. Encapsulating them in an estimator has the same purpose as
    the PolynomialFeatures -> StandardScaler -> regression pipeline in Section 3.14: no
    learned preprocessing is shared between training folds and their held-out observations.
    """

    def __init__(self, degree=5, method="ols", lam=0.0, scale=True, solver=None):
        """Store the hyperparameters (scikit-learn estimator convention)."""
        self.degree = degree
        self.method = method
        self.lam = lam
        self.scale = scale
        self.solver = solver

    def fit(self, x, y):
        """Fit features, scaler and chosen solver using only the observations passed here.

        A resampling caller passes only its current training rows. Recreating Scaler on every
        call follows Section 3.14 / Week 36 Exercise 4, including refitting the intercept.
        """
        X = polynomial_features(x, self.degree)
        self.scaler_ = Scaler(self.scale).fit(X, y)
        Xs = self.scaler_.transform(X)
        yc = self.scaler_.center(np.asarray(y, dtype=float).ravel())
        if self.solver is not None:
            self.theta_ = self.solver(Xs, yc, self.lam)
        elif self.method == "ols":
            self.theta_ = ols_parameters(Xs, yc)
        elif self.method == "ridge":
            self.theta_ = ridge_parameters(Xs, yc, self.lam)
        elif self.method == "lasso":
            self.theta_ = lasso_sklearn_parameters(Xs, yc, self.lam)
        else:
            raise ValueError(f"unknown method {self.method!r}")
        self.intercept_ = self.scaler_.y_mean
        return self

    def predict(self, x):
        """Predict with the training scaler and the fitted coefficients."""
        Xs = self.scaler_.transform(polynomial_features(x, self.degree))
        return self.intercept_ + Xs @ self.theta_
